package main

import (
	"archive/tar"
	"bytes"
	"fmt"
	"io"
	"maps"
)

const (
	pythonTarHeaderTypeOffset = 156
	pythonTarHeaderSumOffset  = 148
	pythonPAXPath             = "path"
	pythonPAXSize             = "size"
)

// The standard tar reader parses global PAX records but does not inherit them.
// Merge their state into each file's local records before decoding that file.
// Physical records and logical file bodies keep independent resource bounds.
type pythonTarState struct {
	global, local map[string]string
	pending       []byte
	entries       []pythonArchiveEntry
	budget        pythonArchiveBudget
	awaitingFile  bool
}

func readPythonTarRecords(records [][]byte) ([]pythonArchiveEntry, bool) {
	state := new(pythonTarState)
	state.global, state.local = make(map[string]string), make(map[string]string)
	for _, record := range records {
		if !state.accept(record) {
			return nil, false
		}
	}
	return state.entries, !state.awaitingFile
}

func (state *pythonTarState) accept(record []byte) bool {
	switch record[pythonTarHeaderTypeOffset] {
	case tar.TypeXGlobalHeader, tar.TypeXHeader:
		records, valid := pythonTarPAXRecords(record)
		if !valid {
			return false
		}
		target := state.local
		if record[pythonTarHeaderTypeOffset] == tar.TypeXGlobalHeader {
			target = state.global
		}
		maps.Copy(target, records)
		state.awaitingFile = true
		return true
	case tar.TypeGNULongName, tar.TypeGNULongLink:
		state.pending = append(state.pending, record...)
		state.awaitingFile = true
		return true
	default:
		return state.readFile(record)
	}
}

func (state *pythonTarState) readFile(record []byte) bool {
	records := maps.Clone(state.global)
	maps.Copy(records, state.local)
	if name, present := records[pythonPAXPath]; present && !safePythonArchiveName(name) {
		return false
	}
	prefix, valid := pythonTarLocalHeader(records)
	if !valid {
		return false
	}
	source := io.MultiReader(bytes.NewReader(prefix), bytes.NewReader(state.pending), bytes.NewReader(record))
	reader := tar.NewReader(source)
	member, err := reader.Next()
	if err != nil || member.Size < 0 || !validPythonTarMember(member) || !state.budget.accept(uint64(member.Size)) {
		return false
	}
	body, err := io.ReadAll(io.LimitReader(reader, pythonArchiveMemberBytes+1))
	if err != nil || int64(len(body)) != member.Size {
		return false
	}
	state.entries = append(state.entries, pythonArchiveEntry{
		name: member.Name, data: body,
		mode: uint32(member.Mode & pythonUnixPermissions), directory: member.Typeflag == tar.TypeDir,
	})
	clear(state.local)
	state.pending = nil
	state.awaitingFile = false
	return true
}

func pythonTarPAXRecords(record []byte) (map[string]string, bool) {
	// A local extended header needs a following file for Next to return it.
	// The placeholder is never read or included in package content.
	header := new(tar.Header)
	header.Name, header.Typeflag = "entry", tar.TypeReg
	placeholder, valid := pythonTarEncodedHeader(header)
	if !valid {
		return nil, false
	}
	reader := tar.NewReader(io.MultiReader(bytes.NewReader(record), bytes.NewReader(placeholder)))
	parsed, err := reader.Next()
	if err != nil {
		return nil, false
	}
	return parsed.PAXRecords, true
}

func pythonTarLocalHeader(records map[string]string) ([]byte, bool) {
	if len(records) == 0 {
		return nil, true
	}
	header := new(tar.Header)
	header.Typeflag, header.PAXRecords = tar.TypeXGlobalHeader, records
	raw, valid := pythonTarEncodedHeader(header)
	if !valid {
		return nil, false
	}
	// Go's writer can emit standalone global headers. Make these freshly
	// generated bytes local and recompute their checksum; input is never patched.
	raw[pythonTarHeaderTypeOffset] = tar.TypeXHeader
	copy(raw[pythonTarHeaderSumOffset:pythonTarHeaderTypeOffset], "        ")
	var sum int
	for _, value := range raw[:pythonTarBlockSize] {
		sum += int(value)
	}
	copy(raw[pythonTarHeaderSumOffset:pythonTarHeaderTypeOffset], fmt.Sprintf("%06o\x00 ", sum))
	return raw, true
}

func pythonTarEncodedHeader(header *tar.Header) ([]byte, bool) {
	var output bytes.Buffer
	writer := tar.NewWriter(&output)
	headerError := writer.WriteHeader(header)
	flushError := writer.Flush()
	return output.Bytes(), headerError == nil && flushError == nil
}
