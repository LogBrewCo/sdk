package main

import (
	"bytes"
	"os"
	"path"
	"path/filepath"
	"testing"
)

func TestBrandOutputBundle(t *testing.T) {
	t.Parallel()
	outputs := make(map[string][]byte)
	for name := range brandGeneratedAssets() {
		outputs[name] = []byte(repositorySource(t, name))
	}
	destination := filepath.Join(t.TempDir(), "generated-assets")
	if !brandWriteOutputBundle(destination, outputs) {
		t.Fatal("generated bundle publication failed")
	}
	entries, err := os.ReadDir(destination)
	if err != nil || len(entries) != len(outputs) {
		t.Fatal("generated bundle inventory incomplete")
	}
	root, err := os.OpenRoot(destination)
	if err != nil {
		t.Fatal("published bundle root unavailable")
	}
	for name, expected := range outputs {
		actual, valid := brandReadAsset(root, path.Base(name), brandSVGByteLimit)
		if !valid || !bytes.Equal(actual, expected) {
			t.Fatal("published generated bytes changed")
		}
	}
	if err := root.Close(); err != nil {
		t.Fatal("published bundle close failed")
	}
	if brandWriteOutputBundle(destination, outputs) {
		t.Fatal("existing output bundle replaced")
	}
	if brandWriteOutputBundle(filepath.Join(t.TempDir(), "invalid"), nil) {
		t.Fatal("invalid output bundle published")
	}
}
